/*
 * "Wayfarer 5×7": an original bitmap font for the gallery (story 3.10), drawn for this repository
 * and MIT licensed with it. Not derived from any existing font.
 *
 * Capitals and digits are 5 × 7 texels; lower case has a 5-row x-height, 2-row ascenders above it
 * and 2-row descenders below the baseline, so every glyph fits a 5 × 9 box with the baseline under
 * row 6. Glyphs are drawn as rows of `#` (ink) and `.` (paper), top row first; rows left out at the
 * bottom are blank. Widths vary: the atlas trims each glyph to its ink, so the text is proportional
 * (an `i` is narrower than an `m`), which reads far better in dialogue than a fixed pitch.
 */

export interface BitmapFont {
  readonly name: string;
  /** Rows from the top of the box to the baseline (cap height). */
  readonly ascent: number;
  /** Rows of the whole box, descenders included. */
  readonly height: number;
  /** Blank columns after each glyph. */
  readonly spacing: number;
  /** Advance of a space, in texels, on top of the spacing after the glyph before it. */
  readonly spaceWidth: number;
  readonly glyphs: Readonly<Record<string, readonly string[]>>;
}

